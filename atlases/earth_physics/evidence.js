// Evidence registry for the atlas map modes: how far each layer (and each settlement/supply
// option) has been tested on real Earth. Source of the tiers and test notes:
// calibration/earth_components_20261105/evidence_spec.json and the reports it cites.
//   earth       Earth-tested: the same model, run on Earth, was scored against held-out data
//   partial     Partly tested: parts scored on Earth, other parts assumed or unscored
//   scenario    Scenario: built from declared assumptions; not scored as a whole
//   experimental, diagnostic: shown only with "Experimental & diagnostics" switched on
