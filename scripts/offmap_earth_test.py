"""How much climate skill the invented off-map land costs, measured on Earth.

    python -I scripts/offmap_earth_test.py --out output/offmap_earth_20261101 [--regions ...] [--methods M0 M1 M2]

For each Earth region the scored window keeps its real land and terrain; the
1,100 km around it (the part an invented map does not know) is either the
real world ("real") or generated by rotclimate.geography's off-map method
with each side's real land share (the map fits these shares; here they are
given, so only the method is tested). Both run in map mode: the Earth-only
derived fields that the map does not have (westward fetch over ~5,000 km,
poleward cold-air reach, sea reach, monsoon descent, sea depth) are set to
None so the model computes them from the grid, and the world beyond the grid
(chi_far) is the real one in every run. The cost of a method is how far its
window climate falls from the real-surroundings run (monthly temperature
RMS, monthly rain log-RMS), averaged over its random layouts as the atlas
averages them.

Methods: M0 the atlas's (3 layouts), M1 the same with 9 layouts, M2 3 layouts
with continent-scale noise (1,500 and 3,000 km added), M3 3 layouts with the
edge continuation over 300 km instead of the fit's 688.
"""
from __future__ import annotations

import argparse
import copy
import json
import os
import sys
from multiprocessing import Pool
from pathlib import Path

os.environ.setdefault("OMP_NUM_THREADS", "1")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "scripts"))
import numpy as np  # noqa: E402

from benchmark_local import DEV12_SPECS  # noqa: E402
from earth_benchmark import load_params  # noqa: E402
from rotclimate import earth  # noqa: E402
from rotclimate import geography as G  # noqa: E402
from rotclimate.koppen import monthly_stats  # noqa: E402
from rotclimate.model import ClimateModel  # noqa: E402

PARAMS = ROOT / "calibration/local_accuracy_20261023/r40_params.json"
REGIONS = ["british_isles", "iberia", "east_china", "japan", "central_asia", "california", "south_brazil", "north_india"]
CONT_KM, RELIEF_M = 687.7, 176.0          # the Earth-fit atlas's fitted continuation and relief
METHODS = {"M0": dict(seeds=[1, 2, 3]), "M1": dict(seeds=list(range(1, 10))),
           "M2": dict(seeds=[1, 2, 3], big=True), "M3": dict(seeds=[1, 2, 3], cont_km=300.0)}


def side_fractions(g):
    """Real land share of the four strips beyond the window (N, S, W, E), the corners split."""
    p = g.pad; land = g.land_frac >= 0.5
    H, W = land.shape
    win = g.inmap
    rows = np.where(win.any(1))[0]; cols = np.where(win.any(0))[0]
    r0, r1, c0, c1 = rows[0], rows[-1] + 1, cols[0], cols[-1] + 1
    return [float(land[:r0, c0:c1].mean()), float(land[r1:, c0:c1].mean()),
            float(land[r0:r1, :c0].mean()), float(land[r0:r1, c1:].mean())], (r0, r1, c0, c1)


def map_mode(g):
    g = copy.copy(g)
    g.chi_far_long = g.chi_pole = g.sea_reach = g.descent = g.sea_depth = None
    return g


def procedural(g, seed, cont_km, big):
    fracs, (r0, r1, c0, c1) = side_fractions(g)
    core = {k: np.asarray(getattr(g, k))[r0:r1, c0:c1].astype(float) for k in ("land_frac", "elev", "elev_max")}
    p_n, p_s, p_w, p_e = r0, g.ny - r1, c0, g.nx - c1
    p = max(p_n, p_s, p_w, p_e)
    raw = getattr(G._noise, "__wrapped__", G._noise)
    old = raw.__defaults__
    if big:
        raw.__defaults__ = ((45.0, 90.0, 180.0, 360.0, 720.0, 1500.0, 3000.0), (0.12, 0.3, 0.45, 0.7, 1.0, 1.0, 0.8)) + old[2:]
    if hasattr(G._noise, "cache_clear"):
        G._noise.cache_clear()
    try:
        fields, inmap = G._procedural_offmap(core, p, g.cell_km, 0.0, ("procedural", tuple(fracs), cont_km, RELIEF_M, seed))
    finally:
        raw.__defaults__ = old
        if hasattr(G._noise, "cache_clear"):
            G._noise.cache_clear()
    # crop the square pad back to this grid's own pads
    sl = (slice(p - p_n, p - p_n + g.ny), slice(p - p_w, p - p_w + g.nx))
    h = copy.copy(g)
    h.land_frac = fields["land_frac"][sl]
    h.land = h.land_frac >= 0.5
    h.elev = np.where(h.land, np.maximum(fields["elev"][sl], 1.0), 0.0)
    h.elev_max = np.where(h.land, np.maximum(fields["elev_max"][sl], h.elev), 0.0)
    return map_mode(h)


def run(job):
    region, method, seed = job
    earth.REGIONS.update(json.loads(DEV12_SPECS.read_text()))
    case = earth.region_case(region, 56.0)
    p = earth.earth_params(load_params(PARAMS), case)
    if method == "real":
        g = map_mode(case.grid)
    else:
        spec = METHODS[method]
        g = procedural(case.grid, seed, spec.get("cont_km", CONT_KM), spec.get("big", False))
    try:
        res = ClimateModel(p, g).run(steps=p.steps_per_year)
    except Exception as error:
        return region, method, seed, None, repr(error)
    st = monthly_stats(res.T, res.P, res.days, p.year_days, summer_solstice=p.winter_solstice_day + p.year_days / 2)
    m = case.grid.inmap & case.grid.land & np.isfinite(case.obs_T).all(0) & np.isfinite(case.obs_P).all(0)
    return region, method, seed, dict(T=st["Tm"][:, m].astype(np.float32), P=np.maximum(st["Pm"][:, m], 0).astype(np.float32),
                                      oT=case.obs_T[:, m].astype(np.float32), oP=case.obs_P[:, m].astype(np.float32)), None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "output/offmap_earth_20261101")
    ap.add_argument("--regions", nargs="+", default=REGIONS)
    ap.add_argument("--methods", nargs="+", default=list(METHODS))
    ap.add_argument("--workers", type=int, default=4)
    a = ap.parse_args(); a.out.mkdir(parents=True, exist_ok=True)
    jobs = [(r, "real", 0) for r in a.regions] + [(r, m, s) for r in a.regions for m in a.methods for s in METHODS[m]["seeds"]]
    got = {}
    with Pool(a.workers) as pool:
        for region, method, seed, rec, err in pool.imap_unordered(run, jobs):
            got[(region, method, seed)] = rec
            print(region, method, seed, "ok" if rec is not None else err, flush=True)
    out = dict(params=str(PARAMS.relative_to(ROOT)), regions={}, summary={})
    lrms = lambda a_, b_: float(np.sqrt(np.mean((np.log((a_ + 10) / (b_ + 10))) ** 2)))
    for r in a.regions:
        real = got.get((r, "real", 0))
        if real is None:
            continue
        row = dict(real_vs_obs=dict(T_mae=float(np.abs(real["T"] - real["oT"]).mean()), P_lrms=lrms(real["P"], real["oP"])))
        for m in a.methods:
            recs = [got.get((r, m, s)) for s in METHODS[m]["seeds"]]
            if any(x is None for x in recs):
                continue
            T = np.mean([x["T"] for x in recs], 0); P = np.mean([x["P"] for x in recs], 0)
            row[m] = dict(T_rms_vs_real=float(np.sqrt(np.mean((T - real["T"]) ** 2))), P_lrms_vs_real=lrms(P, real["P"]),
                          T_mae_vs_obs=float(np.abs(T - real["oT"]).mean()), P_lrms_vs_obs=lrms(P, real["oP"]),
                          single_layout_T_rms=float(np.mean([np.sqrt(np.mean((x["T"] - real["T"]) ** 2)) for x in recs])))
        out["regions"][r] = row
    for m in a.methods:
        vals = [out["regions"][r][m] for r in out["regions"] if m in out["regions"][r]]
        if vals:
            out["summary"][m] = {k: float(np.mean([v[k] for v in vals])) for k in vals[0]}
    (a.out / "offmap.json").write_text(json.dumps(out, indent=1))
    print(json.dumps(out["summary"], indent=1))


if __name__ == "__main__":
    main()
